// PPT generation
router.post('/ppt', authenticateToken, async (req, res) => {
  try {
    const { content, title = 'Generated Presentation', theme = 'default' } = req.body;
    
    const filename = `${uuidv4()}.pptx`;
    const filepath = path.join(__dirname, '../uploads', filename);
    
    // Ensure uploads directory exists
    const uploadsDir = path.dirname(filepath);
    if (!fs.existsSync(uploadsDir)) {
      fs.mkdirSync(uploadsDir, { recursive: true });
    }
    
    // Create PowerPoint presentation
    const pptx = new PptxGenJS();
    
    // Set presentation properties
    pptx.author = 'Kris Bot';
    pptx.company = 'Kris Bot AI';
    pptx.title = title;
    
    // Title slide
    const titleSlide = pptx.addSlide();
    titleSlide.addText(title, {
      x: 1, y: 2, w: 8, h: 1.5,
      fontSize: 32,
      bold: true,
      align: 'center',
      color: '363636'
    });
    titleSlide.addText('Generated by Kris Bot', {
      x: 1, y: 4, w: 8, h: 0.5,
      fontSize: 16,
      align: 'center',
      color: '666666'
    });
    
    // Content slides - split content into slides
    const contentLines = content.split('\n').filter(line => line.trim());
    const slidesContent = [];
    let currentSlide = [];
    
    contentLines.forEach(line => {
      if (line.startsWith('#') || currentSlide.length >= 5) {
        if (currentSlide.length > 0) {
          slidesContent.push(currentSlide);
          currentSlide = [];
        }
      }
      currentSlide.push(line);
    });
    
    if (currentSlide.length > 0) {
      slidesContent.push(currentSlide);
    }
    
    // Add content slides
    slidesContent.forEach((slideContent, index) => {
      const slide = pptx.addSlide();
      
      // Slide title
      const slideTitle = slideContent[0].replace(/^#+\s*/, '') || `Slide ${index + 1}`;
      slide.addText(slideTitle, {
        x: 0.5, y: 0.5, w: 9, h: 1,
        fontSize: 24,
        bold: true,
        color: '363636'
      });
      
      // Slide content
      const bulletPoints = slideContent.slice(1).map(line => line.replace(/^-\s*/, ''));
      if (bulletPoints.length > 0) {
        slide.addText(bulletPoints, {
          x: 0.5, y: 1.8, w: 9, h: 4,
          fontSize: 16,
          bullet: true,
          color: '444444'
        });
      }
    });
    
    // Save presentation
    await pptx.writeFile({ fileName: filepath });
    
    const pptUrl = `/uploads/${filename}`;
    
    // Save to database
    const mediaGen = new MediaGeneration({
      userId: req.userId,
      type: 'ppt',
      prompt: `PPT: ${title}`,
      outputUrl: pptUrl,
      metadata: { theme, title }
    });
    
    await mediaGen.save();
    
    res.json({
      title: `Generated PPT: ${title}`,
      pptUrl,
      filename,
      type: 'ppt'
    });
  } catch (error) {
    res.status(500).json({ message: 'PPT generation failed', error: error.message });
  }
});

